@app.route('/login', methods=['GET', 'POST'])
def login():
    if request.method == 'POST':
        email = request.form.get('email', '').strip().lower()
        password = request.form.get('password', '')
        con = db()
        u = con.execute('SELECT * FROM users WHERE email=%s' if is_postgres() else 'SELECT * FROM users WHERE email=?', (email,)).fetchone()
        if not u or not verify_password(password, u['password']):
            con.close()
            flash('Account not found or incorrect password.', 'error')
            return redirect(url_for('login'))
        con.execute('UPDATE users SET last_login=%s WHERE id=%s' if is_postgres() else 'UPDATE users SET last_login=? WHERE id=?',
                     (datetime.now().isoformat(timespec='seconds'), u['id']))
        con.commit()
        con.close()
        session['user_id'] = u['id']
        session.permanent = bool(request.form.get('remember'))
        return redirect(url_for('dashboard'))
    return render_template('login.html')


@app.route('/signup', methods=['GET', 'POST'])
def signup():
    if request.method == 'POST':
        first = request.form.get('first_name', '').strip()
        last = request.form.get('last_name', '').strip()
        birthday = request.form.get('birthday', '').strip()
        email = request.form.get('email', '').strip().lower()
        password = request.form.get('password', '')
        confirm = request.form.get('confirm_password', request.form.get('confirm', ''))
        if len(first) < 2 or len(last) < 2 or not first.replace(' ', '').isalpha() or not last.replace(' ', '').isalpha():
            flash('Enter valid first and last names.', 'error')
            return render_template('signup.html')
        try:
            b = date.fromisoformat(birthday)
        except ValueError:
            flash('Enter a valid birth date.', 'error')
            return render_template('signup.html')
        age = age_from_birth(b)
        if age < 13:
            flash('You must be at least 13 years old.', 'error')
            return render_template('signup.html')
        if age > 120:
            flash('Please enter a valid birth date.', 'error')
            return render_template('signup.html')
        if '@' not in email or '.' not in email.split('@')[-1]:
            flash('Enter a valid email address.', 'error')
            return render_template('signup.html')
        if len(password) < 8:
            flash('Password must be at least 8 characters.', 'error')
            return render_template('signup.html')
        if password != confirm:
            flash('Passwords do not match.', 'error')
            return render_template('signup.html')

        con = db()
        try:
            if is_postgres():
                cur = con.execute('''INSERT INTO users(email,password,first_name,last_name,birthday,age,created)
                                     VALUES(%s,%s,%s,%s,%s,%s,%s) RETURNING id''',
                                  (email, hash_password(password), first, last, birthday, age,
                                   datetime.now().isoformat(timespec='seconds')))
                user_id = cur.fetchone()['id']
            else:
                cur = con.execute('''INSERT INTO users(email,password,first_name,last_name,birthday,age,created)
                                     VALUES(?,?,?,?,?,?,?)''',
                                  (email, hash_password(password), first, last, birthday, age,
                                   datetime.now().isoformat(timespec='seconds')))
                user_id = cur.lastrowid
            con.commit()
            session['user_id'] = user_id
        except Exception as exc:
            con.rollback()
            con.close()
            if 'unique' in str(exc).lower() or 'duplicate' in str(exc).lower():
                flash('An account with that email already exists.', 'error')
                return render_template('signup.html')
            raise
        con.close()
        return redirect(url_for('welcome'))
    return render_template('signup.html')


