SCHEMA = '''
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    birthday TEXT NOT NULL,
    age INTEGER NOT NULL,
    created TEXT NOT NULL,
    last_login TEXT
);
CREATE TABLE IF NOT EXISTS documents (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    stored_name TEXT NOT NULL,
    original_name TEXT NOT NULL,
    uploaded TEXT NOT NULL,
    size INTEGER NOT NULL,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
'''


def is_postgres():
    return bool(DATABASE_URL)


def pg_url():
    # Some providers still return postgres://. psycopg accepts postgresql://.
    return DATABASE_URL.replace('postgres://', 'postgresql://', 1)


def db():
    if not is_postgres():
        con = sqlite3.connect(SQLITE_DB)
        con.row_factory = sqlite3.Row
        return con

    import psycopg
    from psycopg.rows import dict_row
    con = psycopg.connect(pg_url(), row_factory=dict_row)
    return con


def execute_schema(con):
    if not is_postgres():
        con.executescript(SCHEMA)
        return

    # PostgreSQL uses GENERATED identity columns rather than SQLite's AUTOINCREMENT.
    con.execute('''
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            first_name TEXT NOT NULL,
            last_name TEXT NOT NULL,
            birthday TEXT NOT NULL,
            age INTEGER NOT NULL,
            created TEXT NOT NULL,
            last_login TEXT
        )
    ''')
    con.execute('''
        CREATE TABLE IF NOT EXISTS documents (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            stored_name TEXT NOT NULL,
            original_name TEXT NOT NULL,
            uploaded TEXT NOT NULL,
            size INTEGER NOT NULL
        )
    ''')


def init_db():
    con = db()
    execute_schema(con)
    con.commit()
    con.close()


init_db()


def hash_password(password):
    # PBKDF2 is intentionally used instead of a single fast SHA-256 hash.
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac('sha256', password.encode(), salt, 310_000)
    return 'pbkdf2_sha256$310000$' + salt.hex() + '$' + digest.hex()


def verify_password(password, stored):
    try:
        algorithm, iterations, salt_hex, digest_hex = stored.split('$')
        if algorithm != 'pbkdf2_sha256':
            return False
        digest = hashlib.pbkdf2_hmac('sha256', password.encode(), bytes.fromhex(salt_hex), int(iterations))
        return secrets.compare_digest(digest.hex(), digest_hex)
    except (ValueError, TypeError):
        return False


def age_from_birth(b):
    today = date.today()
    return today.year - b.year - ((today.month, today.day) < (b.month, b.day))


def current_user():
    if 'user_id' not in session:
        return None
    con = db()
    u = con.execute('SELECT * FROM users WHERE id=%s' if is_postgres() else 'SELECT * FROM users WHERE id=?', (session['user_id'],)).fetchone()
    con.close()
    return u


